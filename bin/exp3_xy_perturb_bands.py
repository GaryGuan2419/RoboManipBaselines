# 半宽 h：每轴 U[-h,h]；名义边长约 2h [m] → 标签用 cm 近似。
PERTURB_CM_SPECS = [
    (0.005, "1×1 cm"),
    (0.01, "2×2 cm"),
    (0.015, "3×3 cm"),
    (0.025, "5×5 cm"),
    (0.035, "7×7 cm"),
    (0.04, "8×8 cm"),
    (0.05, "10×10 cm"),
    (0.06, "12×12 cm"),
    (0.075, "15×15 cm"),
]

# Ground baton 等：名义至 12×12 cm 的 8 档（不含 15×15）
PERTURB_CM_SPECS_TO_12 = [s for s in PERTURB_CM_SPECS if s[0] <= 0.06 + 1e-9]
